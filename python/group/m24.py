"""M24 as the automorphism group of our Golay code, a sextet, and Conway's xi.

How the generators were found (T4.1, 2026-08-25)
------------------------------------------------
Our Golay code (kiss_ref.golay) is the cyclic (23,12,7) code generated by
g(x) = x^11+x^10+x^6+x^5+x^4+x^2+1, extended by a parity bit in coordinate 23.
The cyclic code is a quadratic-residue code on Z/23, so the natural labelling

    coordinate k  <->  field element k  (k = 0..22),   coordinate 23  <->  infinity

puts it in "QR form" with NO extra coordinate permutation: it was checked
computationally (search over all 22 multiplier labellings k -> a*k) that the
identity labelling makes every one of the maps below permute the 4096
codewords.  PSL(2,23) acts on P^1(F_23) = F_23 u {inf} by

    alpha : x -> x + 1                     (order 23)
    gamma : x -> -1/x                      (order 2; 0 <-> inf)

and the standard extra generator of M24 (Conway, SPLAG ch. 10 / ATLAS) is

    delta : x -> x^3 / 9  for x a quadratic residue (incl. 0),
            x -> 9 x^3    for x a non-residue,      inf fixed   (order 5).

The variant with the roles of residues and non-residues swapped does NOT
preserve our code (it preserves the equivalent code on the multiplier
labellings k -> a*k with a a non-residue); this is asserted in the tests.
<alpha, gamma> has order 6072 = |PSL(2,23)|; <alpha, gamma, delta> has order
244,823,040 = |M24| (sympy Schreier-Sims).  The only proof that matters is
that each generator permutes the codeword set; ``preserves_code`` checks it.

Sextet and xi
-------------
``find_sextet`` builds the sextet through a tetrad T (default {0,1,2,3}): for
each point p outside T the unique octad containing T u {p} gives another
tetrad.  Conway's xi acts on each tetrad by the block (1/2)(J - 2I), i.e.
x_i -> (sum over the tetrad)/2 - x_i, with a sign twist: the block is negated
on an ODD number of tetrads (we negate it on the first).  ``verify_aut`` was
used to test all 2^5 sign patterns (up to global sign): the uniform pattern
maps only 49104 of the 196560 minimal vectors back into the set, every
odd-negation pattern is a bijection of the minimal vectors.
"""

