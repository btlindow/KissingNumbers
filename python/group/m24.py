def write_generators(path: str) -> None:
    gens = m24_generators()
    names = ["alpha: x -> x+1", "gamma: x -> -1/x", "delta: x -> x^3/9 (Q), 9x^3 (N)"]
    with open(path, "w") as f:
        f.write("# M24 generators as coordinate permutations of our Golay code (bit i = coordinate i).\n")
        f.write("# One permutation per line: images of coordinates 0..23.  Coordinate k <-> k in F_23, 23 <-> inf.\n")
        f.write("# Generated by python/group/m24.py; each line verified to permute the 4096 codewords;\n")
        f.write("# <alpha,gamma> has order 6072 = |PSL(2,23)|, <alpha,gamma,delta> has order 244823040 = |M24|.\n")
        for name, g in zip(names, gens):
            assert preserves_code(g)
            f.write(" ".join(str(v) for v in g) + f"   # {name}\n")


def write_xi(path: str, sextet_path: str | None = None) -> None:
    sextet = find_sextet()
    num = xi_numerators(sextet)
    n_in, bij = verify_aut(num, 2)
    assert n_in == 196560 and bij, (n_in, bij)
    with open(path, "w") as f:
        f.write("# Conway's xi for the sextet below: on tetrad T, x_i -> s_T * ((sum_{j in T} x_j)/2 - x_i).\n")
        f.write("# sextet: " + " | ".join(" ".join(str(i) for i in t) for t in sextet) + "\n")
        f.write("# tetrad signs s_T: " + " ".join(str(s) for s in XI_TETRAD_SIGNS) + "\n")
        f.write("# Verified (python/group/m24.py): maps all 196560 minimal vectors bijectively onto themselves.\n")
        f.write("# Format: 'den D' then 24 rows of 24 integer numerators; (xi v)[r] = sum_c num[r][c] v[c] / D.\n")
        f.write("den 2\n")
        for row in num:
            f.write(" ".join(f"{v:2d}" for v in row) + "\n")
    if sextet_path:
        with open(sextet_path, "w") as f:
            f.write("# Sextet of our Golay code through the tetrad {0,1,2,3}: one tetrad per line;\n")
            f.write("# the union of any two tetrads is an octad.\n")
            for t in sextet:
                f.write(" ".join(str(i) for i in t) + "\n")


def main(argv: Sequence[str] | None = None) -> int:
    import argparse

    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "..", "data", "group"))
    args = ap.parse_args(argv)
    os.makedirs(args.out, exist_ok=True)
    gens = m24_generators()
    for g in gens:
        assert preserves_code(g)
    order = group_order(gens)
    assert order == M24_ORDER, order
    write_generators(os.path.join(args.out, "m24_generators.txt"))
    write_xi(os.path.join(args.out, "xi.txt"), os.path.join(args.out, "sextet.txt"))
    print(f"RESULT ok=1 m24_order={order} psl_order={group_order(list(psl_generators()))} out={args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
