def _bits(mask: int) -> list[int]:
    return [i for i in range(24) if (mask >> i) & 1]


def find_sextet(tetrad: Sequence[int] = (0, 1, 2, 3)) -> list[list[int]]:
    """The sextet containing ``tetrad``: 6 tetrads, any two forming an octad."""
    t0 = sorted(int(i) for i in tetrad)
    assert len(t0) == 4 and all(0 <= i < 24 for i in t0)
    octs = octads()
    m0 = sum(1 << i for i in t0)
    tetrads = [t0]
    used = set(t0)
    while len(used) < 24:
        p = min(set(range(24)) - used)
        m = m0 | (1 << p)
        oc = [o for o in octs if (o & m) == m]
        assert len(oc) == 1, "S(5,8,24): T u {p} lies in exactly one octad"
        t = [i for i in _bits(oc[0]) if i not in used and i not in t0]
        assert len(t) == 4
        tetrads.append(t)
        used |= set(t)
    oset = set(octs)
    for a, b in combinations(tetrads, 2):
        assert sum(1 << i for i in a + b) in oset
    return tetrads


#: Sign of the (1/2)(J - 2I) block on each tetrad of the chosen xi.
XI_TETRAD_SIGNS = (-1, 1, 1, 1, 1, 1)


def xi_numerators(sextet: Sequence[Sequence[int]], signs: Sequence[int] = XI_TETRAD_SIGNS) -> list[list[int]]:
    """24x24 integer numerators of xi over the common denominator 2.

    Row r, column c: (xi v)[r] = sum_c num[r][c] v[c] / 2.  On tetrad T with
    sign s the block is s * (J - 2I), i.e. s for r != c in T, -s for r == c.
    """
    num = [[0] * 24 for _ in range(24)]
    for t, s in zip(sextet, signs):
        for r in t:
            for c in t:
                num[r][c] = int(s) * (-1 if r == c else 1)
    return num


def verify_aut(num: Sequence[Sequence[int]], den: int) -> tuple[int, bool]:
    """Apply (num/den) to all 196560 minimal vectors.

    Returns (number of images that are minimal vectors, bijection?).  An image
    with a non-integer coordinate counts as "not in C".
    """
    import numpy as np

    from kiss_ref.leech import leech_min_vectors

    C8 = leech_min_vectors()
    C = C8.astype(np.int64)
    M = np.asarray(num, dtype=np.int64)
    img = C @ M.T
    ok_int = np.all(img % den == 0, axis=1)
    img = img // den
    keys = np.ascontiguousarray(C8).view(np.dtype((np.void, 24))).ravel()
    order = np.argsort(keys)
    sk = keys[order]
    small = np.all(np.abs(img) <= 127, axis=1)
    img8 = np.clip(img, -127, 127).astype(np.int8)
    k = np.ascontiguousarray(img8).view(np.dtype((np.void, 24))).ravel()
    pos = np.minimum(np.searchsorted(sk, k), len(sk) - 1)
    hit = (sk[pos] == k) & ok_int & small
    idx = np.where(hit, order[pos], -1)
    n_in = int(hit.sum())
    bij = n_in == len(C) and len(np.unique(idx)) == len(C)
    return n_in, bij


