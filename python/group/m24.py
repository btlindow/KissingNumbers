P = 23
M24_ORDER = 244_823_040
PSL_ORDER = 6072
INF = None  # the point at infinity of P^1(F_23), coordinate 23

QUADRATIC_RESIDUES = frozenset((x * x) % P for x in range(1, P))
_INV = {x: pow(x, P - 2, P) for x in range(1, P)}


def _coord_to_point(i: int):
    return INF if i == 23 else i


def _point_to_coord(x) -> int:
    return 23 if x is INF else x % P


def _perm_from_map(f: Callable) -> list[int]:
    """perm[i] = image of coordinate i under the map f on P^1(F_23)."""
    perm = [_point_to_coord(f(_coord_to_point(i))) for i in range(24)]
    assert sorted(perm) == list(range(24)), "not a permutation"
    return perm


def permute_mask(mask: int, perm: Sequence[int]) -> int:
    """Move bit i of ``mask`` to position perm[i]."""
    out = 0
    for i in range(24):
        if (mask >> i) & 1:
            out |= 1 << perm[i]
    return out


def preserves_code(perm: Sequence[int], words: Iterable[int] | None = None) -> bool:
    """True iff the coordinate permutation maps every codeword to a codeword."""
    words = list(golay_codewords() if words is None else words)
    s = set(words)
    return all(permute_mask(w, perm) in s for w in words)


def _alpha(x):
    return INF if x is INF else (x + 1) % P


def _gamma(x):
    if x is INF:
        return 0
    if x == 0:
        return INF
    return (-_INV[x]) % P


def psl_generators() -> tuple[list[int], list[int]]:
    """(alpha, gamma) = (x -> x+1, x -> -1/x) as coordinate permutations."""
    return _perm_from_map(_alpha), _perm_from_map(_gamma)


def delta(swap: bool = False) -> list[int]:
    """x -> x^3/9 on residues (and 0), 9x^3 on non-residues, inf fixed.

    ``swap=True`` exchanges the two rules; that variant does not preserve our
    code and is only exposed so the tests can assert it.
    """

    def f(x):
        if x is INF:
            return INF
        if x == 0:
            return 0
        c = pow(x, 3, P)
        is_q = x in QUADRATIC_RESIDUES
        if swap:
            is_q = not is_q
        return (c * _INV[9]) % P if is_q else (9 * c) % P

    return _perm_from_map(f)


def m24_generators() -> list[list[int]]:
    """[alpha, gamma, delta] — verified generators of M24 = Aut(G24)."""
    a, g = psl_generators()
    return [a, g, delta()]


def group_order(gens: Sequence[Sequence[int]]) -> int:
    """Order of the permutation group generated by ``gens`` (sympy Schreier-Sims)."""
    from sympy.combinatorics import Permutation, PermutationGroup

    return int(PermutationGroup([Permutation(list(g)) for g in gens]).order())


