def s4h_rook(sum_vecs, types, cross_masks, ts):
    """Within a channel the 64 orbits form an 8x8 rook grid (rows = u-pairs of
    one block, cols = w-pairs of the other; sharing a row or column forces a
    dot-16 conflict since +-64/4 = +-16 appears among the sign choices).
    Verify S's orbits form partial permutation matrices in every channel."""
    t0 = time.time()
    groups: dict[tuple, list[int]] = {}
    for oi, (t, c) in enumerate(zip(types, cross_masks)):
        groups.setdefault((t, c), []).append(oi)
    ok = True
    full = half = 0
    for (t, c), ois in groups.items():
        rows_by_block: dict[int, set] = {}
        for oi in ois:
            for w in (sum_vecs[2 * oi], sum_vecs[2 * oi + 1]):
                bi = next(i for i, M in enumerate(ts)
                          if np.array_equal((w @ M.T) // 8, -w))
                rows_by_block.setdefault(bi, set()).add(apair_key(w))
        assert len(rows_by_block) == 2
        for bi, keys in rows_by_block.items():
            if len(keys) != len(ois):
                ok = False
        if len(ois) == 8:
            full += 1
        elif len(ois) == 4:
            half += 1
    # channel-level: orbits of one channel across ALL pairs form a matching in
    # K_{8,8,8} (rows = the 8 +-pairs of the channel's frame in each block;
    # two orbits sharing a row conflict at dot 16 by exact arithmetic)
    ch_groups: dict[int, list[int]] = {}
    for oi, c in enumerate(cross_masks):
        ch_groups.setdefault(c, []).append(oi)
    matching_ok = True
    perfect = 0
    totals = Counter()
    for c, ois in ch_groups.items():
        rows_by_block: dict[int, list] = {}
        for oi in ois:
            for w in (sum_vecs[2 * oi], sum_vecs[2 * oi + 1]):
                bi = next(i for i, M in enumerate(ts)
                          if np.array_equal((w @ M.T) // 8, -w))
                rows_by_block.setdefault(bi, []).append(apair_key(w))
        for bi, keys in rows_by_block.items():
            if len(keys) != len(set(keys)):
                matching_ok = False
        totals[len(ois)] += 1
        if len(ois) == 12:
            assert sorted(len(set(v)) for v in rows_by_block.values()) == [8, 8, 8]
            perfect += 1
    result("S4h", cells_full_permutation=full, cells_half=half,
           usage_is_partial_permutation_in_every_cell=ok,
           channel_orbit_totals=str(dict(sorted(totals.items()))),
           channelwise_K888_matching=matching_ok,
           frame_channels_are_perfect_matchings=perfect,
           note="124 = 3 frame channels x 12 (perfect matchings of K888) "
                "+ 9 channels x 8 (one-pair permutations) + 2 channels x (4+4)",
           seconds=round(time.time() - t0, 1))


def s3d_pair_graph(S, V, tup, smask):
    """The single-pair duad graph: 3840 duads on pair {B2,B3} (t1-fixed),
    conflict = dot 16.  Degree structure, spectral (Hoffman) bound (float,
    labelled non-rigorous), and maximality of S's 208 within the pair."""
    t0 = time.time()
    sel = (tup[:, 0] == 0) & (tup[:, 1] == 16) & (tup[:, 2] == 16)
    D1 = V[sel]
    assert len(D1) == 3840
    in_S = smask[sel]
    assert int(in_S.sum()) == 208
    G = D1.astype(np.float64) @ D1.astype(np.float64).T
    A = (G == 16).astype(np.float64)
    deg = A.sum(axis=1)
    degs = sorted(set(int(d) for d in deg))
    hoffman = None
    if len(degs) == 1:
        d = degs[0]
        ev = np.linalg.eigvalsh(A)
        lmin = float(ev[0])
        hoffman = 3840 * (-lmin) / (d - lmin)
    # maximality of the 208 within the pair (exclude +-S members themselves)
    SD = D1[in_S].astype(np.float64)
    conf = ((D1.astype(np.float64) @ SD.T) == 16).sum(axis=1)
    skey = {apair_key(v) for v in D1[in_S]}
    outside = np.array([apair_key(v) not in skey for v in D1])
    min_conf_outside = int(conf[outside].min())
    result("S3d", pair_duads=3840, S_on_pair=208, degrees=str(degs),
           hoffman_bound_float=(round(hoffman, 2) if hoffman else "n/a (irregular)"),
           min_conflicts_outside_pairS=min_conf_outside,
           S208_maximal_within_pair=bool(min_conf_outside > 0),
           seconds=round(time.time() - t0, 1))


