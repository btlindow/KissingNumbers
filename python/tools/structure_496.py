def s4d_channels(blocks, IB8, types, cross_masks):
    """Glue channels: norm-64 vectors of each block classified mod 2Lambda.
    A duad orbit on pair {j,k} is a pair (u, w), u in B_j, w in B_k, norm 64,
    with u = w mod 2Lambda; the common class is the orbit's 'channel'."""
    t0 = time.time()
    pw = (1 << np.arange(24, dtype=np.int64))
    block_classes = []
    frames_orthogonal = True
    for i, Kb in enumerate(blocks):
        vecs = short_vectors_list(Kb @ Kb.T, 64)
        v64 = np.array([c for nrm, c in vecs if nrm == 64]) @ Kb
        assert len(v64) == 2160
        C = coords_of(v64, IB8) % 2
        masks = (C * pw).sum(axis=1)
        cnt = Counter(int(m) for m in masks)
        # each class holds an even number of vectors (+-v same class)
        pairs = {m: c // 2 for m, c in cnt.items()}
        block_classes.append(pairs)
        # each class = a frame of 8 mutually orthogonal +-pairs (rook rows)
        by_class: dict[int, list] = {}
        for m, v in zip(masks, v64):
            by_class.setdefault(int(m), []).append(v)
        for m, vs in by_class.items():
            vs = np.array(vs)
            gg = vs @ vs.T
            if not np.all(np.isin(gg, [0, 64, -64])):
                frames_orthogonal = False
        result("S4d", block=i + 1, norm64_vectors=2160, distinct_classes=len(pairs),
               pairs_per_class=str(dict(Counter(pairs.values()))),
               classes_are_orthogonal_frames=frames_orthogonal)
    # shared channels per block pair and availability
    avail = {}
    shared_sets = {}
    for t, (j, k) in enumerate([(1, 2), (0, 2), (0, 1)]):
        shared = set(block_classes[j]) & set(block_classes[k])
        total = sum(block_classes[j][c] * block_classes[k][c] for c in shared)
        avail[t] = (len(shared), total)
        shared_sets[t] = shared
        result("S4e", pair=f"B{j+1}+B{k+1}", shared_channels=len(shared),
               available_orbits=total, available_duads=4 * total)
    inter3 = shared_sets[0] & shared_sets[1] & shared_sets[2]
    union3 = shared_sets[0] | shared_sets[1] | shared_sets[2]
    rank_u = gf2_rank(sorted(union3))
    with0 = union3 | {0}
    closed = all((x ^ y) in with0 for x in with0 for y in with0)
    result("S4e2", channels_common_to_all_pairs=len(inter3),
           channels_union=len(union3), union_gf2_rank=rank_u,
           union_closed_under_xor=closed,
           union_is_subspace_minus_0=bool(closed and len(union3) == 2 ** rank_u - 1),
           pair_sets_identical=bool(shared_sets[0] == shared_sets[1] == shared_sets[2]))
    # S usage per (pair, channel)
    usage = Counter((t, m) for t, m in zip(types, cross_masks))
    per_pair_channels = {t: sorted(v for (tt, v) in usage if tt == t) for t in range(3)}
    use_hist = {t: sorted(usage[(t, c)] for c in set(per_pair_channels[t]))
                for t in range(3)}
    result("S4f", S_channels_used=str({t: len(set(per_pair_channels[t])) for t in range(3)}),
           S_usage_per_channel=str(use_hist))
    # the 4-dim span of the S-channels: which elements are unused?
    span = gf2_span(sorted(set(cross_masks)))
    words = [0]
    for bvec in span:
        words = words + [w ^ bvec for w in words]
    unused = [w for w in words if w and w not in set(cross_masks)]
    # are the unused elements channels at all (classes of block norm-64 vectors)?
    all_ch = set().union(*[set(bc) for bc in block_classes])
    result("S4g", cross_span_size=len(words), crosses_used=len(set(cross_masks)),
           span_elements_unused=len(unused),
           unused_are_valid_channels=str([w in all_ch for w in unused]),
           seconds=round(time.time() - t0, 1))
    with open(os.path.join(RUNS, "channels.json"), "w") as f:
        json.dump({"blocks": [{str(k): v for k, v in bc.items()} for bc in block_classes],
                   "usage": {f"{t},{m}": c for (t, m), c in usage.items()}}, f, indent=1)
    return block_classes, sorted(union3)


