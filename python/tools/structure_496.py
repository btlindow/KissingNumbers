def extgcd(a: int, b: int) -> tuple[int, int, int]:
    """g, x, y with x*a + y*b = g = gcd(a, b) >= 0."""
    old_r, r = a, b
    old_s, s = 1, 0
    old_t, t = 0, 1
    while r:
        q = old_r // r
        old_r, r = r, old_r - q * r
        old_s, s = s, old_s - q * s
        old_t, t = t, old_t - q * t
    if old_r < 0:
        old_r, old_s, old_t = -old_r, -old_s, -old_t
    return old_r, old_s, old_t


class Echelon:
    """Row echelon over Z by unimodular row operations, restricted to the first
    `ncols` columns (extra columns are carried along, e.g. a transform tail).

    insert(row) returns None if the row created a new pivot, else the fully
    reduced row (zero in the first ncols columns; its tail is a left-kernel
    contribution when the tails started as unit vectors)."""

    def __init__(self, ncols: int):
        self.ncols = ncols
        self.pivots: dict[int, list[int]] = {}

    def insert(self, row):
        r = [int(v) for v in row]
        n = self.ncols
        for c in range(n):
            if r[c] == 0:
                continue
            p = self.pivots.get(c)
            if p is None:
                self.pivots[c] = r
                return None
            a, b = p[c], r[c]
            g, x, y = extgcd(a, b)
            newp = [x * pi + y * ri for pi, ri in zip(p, r)]
            r = [(a // g) * ri - (b // g) * pi for pi, ri in zip(p, r)]
            self.pivots[c] = newp
        return r

    def det_first_block(self) -> int:
        if len(self.pivots) < self.ncols:
            return 0
        d = 1
        for c in range(self.ncols):
            d *= abs(self.pivots[c][c])
        return d

    def hnf_rows(self) -> list[list[int]]:
        """Pivot rows in column order, pivots positive, entries above pivots
        reduced — the row HNF of the inserted lattice."""
        cols = sorted(self.pivots)
        rows = []
        for c in cols:
            r = self.pivots[c][:]
            if r[c] < 0:
                r = [-v for v in r]
            rows.append(r)
        for j in range(len(rows)):
            for i in range(j + 1, len(rows)):
                c = cols[i]
                p = rows[i][c]
                q = rows[j][c] // p
                if q:
                    rows[j] = [vj - q * vi for vj, vi in zip(rows[j], rows[i])]
        return rows


def lattice_hnf(rows) -> tuple[list[list[int]], int]:
    """Row HNF of the lattice generated by integer rows; (hnf rows, index) with
    index = product of pivots if full column rank, else 0."""
    rows = np.asarray(rows)
    ech = Echelon(rows.shape[1])
    for r in rows:
        ech.insert(r)
    return ech.hnf_rows(), ech.det_first_block()


def left_kernel(A) -> list[list[int]]:
    """Basis (exact, saturated) of {c in Z^m : c A = 0} for an m x n integer
    matrix A, via unimodular row reduction of [A | I]."""
    A = [[int(v) for v in row] for row in A]
    m, n = len(A), len(A[0])
    ech = Echelon(n)
    kern = []
    for i in range(m):
        tail = [0] * m
        tail[i] = 1
        out = ech.insert(A[i] + tail)
        if out is not None:
            kern.append(out[n:])
    return kern


def int_det(M) -> int:
    """Exact determinant of a square integer matrix (fraction-free Bareiss)."""
    a = [[int(v) for v in row] for row in M]
    n = len(a)
    sign = 1
    prev = 1
    for k in range(n - 1):
        if a[k][k] == 0:
            for i in range(k + 1, n):
                if a[i][k]:
                    a[k], a[i] = a[i], a[k]
                    sign = -sign
                    break
            else:
                return 0
        for i in range(k + 1, n):
            for j in range(k + 1, n):
                a[i][j] = (a[i][j] * a[k][k] - a[i][k] * a[k][j]) // prev
        prev = a[k][k]
    return sign * a[n - 1][n - 1]


def smith_invariants(rows) -> list[int]:
    """Nontrivial invariant factors of Z^n / (lattice generated by rows)."""
    import sympy
    from sympy.matrices.normalforms import smith_normal_form

    H, idx = lattice_hnf(rows)
    assert idx != 0, "smith_invariants expects a full-rank lattice"
    snf = smith_normal_form(sympy.Matrix(H))
    diag = [int(snf[i, i]) for i in range(snf.rows)]
    return [d for d in diag if d != 1]


def short_vectors_count(G, bound: int) -> dict[int, int]:
    """Histogram {norm: count} of nonzero lattice vectors with norm <= bound
    for integer Gram G (counting +-v as 2): Fincke-Pohst on a float Cholesky
    factor, every candidate re-checked with exact integer arithmetic."""
    G = np.asarray(G, dtype=np.int64)
    n = G.shape[0]
    L = np.linalg.cholesky(G.astype(np.float64))
    R = L.T
    hist: dict[int, int] = {}
    x = np.zeros(n, dtype=np.int64)

    def rec(k: int, partial: np.ndarray, rem: float):
        if k < 0:
            nrm = int(x @ G @ x)
            if 0 < nrm <= bound:
                hist[nrm] = hist.get(nrm, 0) + 1
            return
        rkk = R[k, k]
        centre = -partial[k] / rkk
        half = (max(rem, 0.0) ** 0.5) / rkk + 1e-6
        lo = int(np.ceil(centre - half))
        hi = int(np.floor(centre + half))
        for xv in range(lo, hi + 1):
            x[k] = xv
            t = rkk * xv + partial[k]
            rem2 = rem - t * t
            if rem2 < -0.5:
                x[k] = 0
                continue
            rec(k - 1, partial + R[:, k] * xv, max(rem2, 0.0))
        x[k] = 0

    # slack 0.9: every candidate is re-checked exactly, so slop cannot overcount
    rec(n - 1, np.zeros(n), float(bound) + 0.9)
    return dict(sorted(hist.items()))


def gf2_span(masks) -> list[int]:
    basis: list[int] = []
    for m in masks:
        for b in basis:
            m = min(m, m ^ b)
        if m:
            basis.append(m)
            basis.sort(reverse=True)
    return basis


def gf2_rank(masks) -> int:
    return len(gf2_span(masks))


def apair_key(v) -> tuple:
    """Canonical key for the antipodal pair {v, -v} (lexicographic min)."""
    a = tuple(int(x) for x in v)
    b = tuple(-x for x in a)
    return min(a, b)


