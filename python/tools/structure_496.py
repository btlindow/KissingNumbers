def s5b_min_vectors_of_gen(S, V, IB8, tup, smask, t4_vectors):
    """Decisive hypothesis test: is S the set of minimal vectors of the
    sublattice <S>_Z?  Since Lambda/<S> = (Z/2)^4, we have 2Lambda <= <S> and
    membership of v in <S> depends only on the class of v mod 2Lambda:
    v in <S>  iff  class(v) lies in the GF(2)-span W of the S-classes."""
    t0 = time.time()
    CS = coords_of(S, IB8) % 2
    pw = (1 << np.arange(24, dtype=np.int64))
    s_masks = sorted({int(m) for m in (CS * pw).sum(axis=1)})
    W = gf2_span(s_masks)
    assert len(W) == 20

    CV = coords_of(V, IB8) % 2
    v_masks = (CV * pw).sum(axis=1)

    def in_span(m):
        m = int(m)
        for bvec in W:
            m = min(m, m ^ bvec)
        return m == 0

    member = np.fromiter((in_span(m) for m in v_masks), dtype=bool, count=len(V))
    n_min = int(member.sum())
    n_in_S = int((member & smask).sum())
    assert n_in_S == 496
    # breakdown of the extra minimal vectors of <S> by block pattern
    extra = member & ~smask
    extra_tup = tup[extra]
    eu, ec = np.unique(extra_tup, axis=0, return_counts=True)
    extra_hist = {str(tuple(int(x) for x in u)): int(c) for u, c in zip(eu, ec)}
    # are the 80 tightness-4 vertices in <S>?
    C4 = coords_of(t4_vectors, IB8) % 2
    t4_masks = (C4 * pw).sum(axis=1)
    t4_in = sum(1 for m in t4_masks if in_span(m))
    result("S5b", min_vectors_of_genS=n_min, of_which_in_S=n_in_S,
           S_equals_min_of_genS=bool(n_min == 496),
           extra_min_vectors=n_min - 496, extra_by_pattern=str(extra_hist),
           t4_in_genS=t4_in, seconds=round(time.time() - t0, 1))
    return member


def short_vectors_list(G, bound: int):
    """All nonzero coefficient vectors with norm <= bound (both signs)."""
    G = np.asarray(G, dtype=np.int64)
    n = G.shape[0]
    R = np.linalg.cholesky(G.astype(np.float64)).T
    out = []
    x = np.zeros(n, dtype=np.int64)

    def rec(k: int, partial: np.ndarray, rem: float):
        if k < 0:
            nrm = int(x @ G @ x)
            if 0 < nrm <= bound:
                out.append((nrm, x.copy()))
            return
        rkk = R[k, k]
        centre = -partial[k] / rkk
        half = (max(rem, 0.0) ** 0.5) / rkk + 1e-6
        for xv in range(int(np.ceil(centre - half)), int(np.floor(centre + half)) + 1):
            x[k] = xv
            t = rkk * xv + partial[k]
            rem2 = rem - t * t
            if rem2 < -0.5:
                x[k] = 0
                continue
            rec(k - 1, partial + R[:, k] * xv, max(rem2, 0.0))
        x[k] = 0

    rec(n - 1, np.zeros(n), float(bound) + 0.9)
    return out


