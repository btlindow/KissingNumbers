def load_stab_elements() -> list[np.ndarray]:
    path = os.path.join(ROOT, "runs", "orbits", "stab496", "co0_stabiliser_elements.txt")
    if not os.path.exists(path):
        import subprocess
        print("stabiliser file missing; regenerating via python/tools/stabilizer_496.py ...")
        subprocess.run([sys.executable, os.path.join(ROOT, "python", "tools", "stabilizer_496.py"),
                        os.path.join(ROOT, "data", "S496.txt"),
                        "--out", os.path.join(ROOT, "runs", "orbits", "stab496")],
                       check=True, cwd=ROOT)
    mats, cur = [], []
    with open(path) as f:
        for line in f:
            line = line.strip()
